#!/usr/bin/env python3
"""Build emoji/emoji.tsv, the emoji picker's catalogue, from Unicode's data.

    tools/emoji-gen.py emoji-test.txt annotations/en.xml annotationsDerived/en.xml \
        > emoji/emoji.tsv

The inputs, from the release the header of the output names:
    https://unicode.org/Public/emoji/latest/emoji-test.txt
    https://github.com/unicode-org/cldr/blob/main/common/annotations/en.xml
    https://github.com/unicode-org/cldr/blob/main/common/annotationsDerived/en.xml

One line per emoji the picker shows, in Unicode's own order, tab-separated:
    group  emoji  name  keywords  variants
keywords are CLDR's, joined by "|"; variants are the skin-tone forms of the
emoji, space-separated, and empty for one that has none: five, light to dark,
or for a pair 25, a square with a row per first person's tone (see tone_key).
A tone form is never a line of its own: the picker offers it from its base.

Only fully-qualified sequences are kept, and the Component group (the bare
tone swatches and hair parts) is dropped, since nobody reacts with one.
"""

import re
import sys
import xml.etree.ElementTree as ET

GROUPS = {
    'Smileys & Emotion': 'smileys',
    'People & Body': 'people',
    'Animals & Nature': 'nature',
    'Food & Drink': 'food',
    'Travel & Places': 'travel',
    'Activities': 'activities',
    'Objects': 'objects',
    'Symbols': 'symbols',
    'Flags': 'flags',
}

TONES = {'light skin tone', 'medium-light skin tone', 'medium skin tone',
         'medium-dark skin tone', 'dark skin tone'}


def base_name(name):
    """The name of the emoji a tone form belongs to.

    Tones are items in the list after the colon, alongside whatever else
    tells the variants apart: "man: medium skin tone, red hair" is a form of
    "man: red hair", and "kiss: woman, man, dark skin tone" of
    "kiss: woman, man".
    """
    head, sep, rest = name.partition(': ')
    if not sep:
        return name
    kept = [p for p in rest.split(', ') if p not in TONES]
    return head + (': ' + ', '.join(kept) if kept else '')


def tone_key(emoji):
    """Where a tone form sits in its base's 5x5 square: (first, second).

    A pair takes one tone for each person, and the forms that have both the
    same are spelled differently from the rest (U+1F91D with one tone, against
    two hands joined), which Unicode lists before the mixed ones for some
    emoji and along the diagonal for others. Sorting on the tones themselves
    puts every square in the same order, and a single tone on the diagonal.
    """
    tones = [ord(c) for c in emoji if 0x1F3FB <= ord(c) <= 0x1F3FF]
    return (tones[0], tones[-1])


def annotations(*paths):
    """CLDR's keywords by emoji, keyed without variation selectors."""
    words = {}
    for path in paths:
        for a in ET.parse(path).getroot().iter('annotation'):
            if a.get('type') == 'tts' or not a.text:
                continue
            words.setdefault(a.get('cp'), [])
            for w in a.text.split('|'):
                w = w.strip()
                if w and w not in words[a.get('cp')]:
                    words[a.get('cp')].append(w)
    return words


def main(test_path, *cldr_paths):
    words = annotations(*cldr_paths)
    version = ''
    group = None
    rows = []          # [group, emoji, name, variants]
    by_name = {}       # name -> row, for the tone forms to find their base

    for line in open(test_path, encoding='utf-8'):
        line = line.rstrip('\n')
        if line.startswith('# Version:'):
            version = line.split(':', 1)[1].strip()
        if line.startswith('# group:'):
            group = GROUPS.get(line.split(':', 1)[1].strip())
            continue
        if not line or line.startswith('#') or group is None:
            continue
        m = re.match(r'^[0-9A-F ]+;\s*(\S+)\s*#\s*(\S+) E\d+\.\d+ (.+)$', line)
        if not m or m.group(1) != 'fully-qualified':
            continue
        emoji, name = m.group(2), m.group(3)

        base = base_name(name)
        if base != name:
            # Unicode lists the forms right after their base. A mixed pair
            # says "person, person" where its base says nothing at all:
            # "kiss: person, person, dark skin tone, ..." is a "kiss".
            owner = by_name.get(base) or by_name.get(base.partition(': ')[0])
            if owner is None:
                sys.exit('no base %r for %r' % (base, name))
            owner[3].append(emoji)
            continue
        row = [group, emoji, name, []]
        rows.append(row)
        by_name[name] = row

    out = sys.stdout
    out.write('# Generated by tools/emoji-gen.py from emoji-test.txt %s and\n'
              '# CLDR annotations; regenerate rather than edit.\n' % version)
    for group, emoji, name, variants in rows:
        kw = words.get(emoji.replace('️', ''), [])
        kw = [w for w in kw if w.lower() != name.lower()]
        out.write('\t'.join([group, emoji, name, '|'.join(kw),
                             ' '.join(sorted(variants, key=tone_key))]) + '\n')


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
